# =============================================================================
# Synthetic example data.
#
# edaphos used to ship real soil profiles -- ISRIC WoSIS extracts, a SoilData
# Dataverse calibration set -- inside inst/extdata. It no longer does. Examples,
# tests and vignettes run on the two simulated fixtures reached through
# edaphos_example_profiles(); real data is the user's to fetch.
#
# One accessor across every example, test and vignette means a future schema
# change is one edit rather than thirty.
# =============================================================================

.edaphos_fixture_files <- c(
  wosis_like    = "fixture_wosis_like.rds",
  soildata_like = "fixture_soildata_like.rds"
)

# Message once per session, not once per call: the danger of a fixture is not
# licensing, it is that a reader mistakes a demo number for a result.
.edaphos_fixture_env <- new.env(parent = emptyenv())

.edaphos_fixture_announce <- function() {
  if (isTRUE(.edaphos_fixture_env$announced)) return(invisible(NULL))
  .edaphos_fixture_env$announced <- TRUE
  packageStartupMessage(
    "edaphos: returning SIMULATED profiles for demonstration.\n",
    "  These are not measurements. Fetch real data yourself; see ",
    "`vignette(\"getting-started\")`."
  )
  invisible(NULL)
}

#' Simulated soil profiles for examples and tests
#'
#' Returns synthetic soil profile data with the same shape as an ISRIC WoSIS
#' extract (`kind = "wosis_like"`) or a SoilData Dataverse bulk-density
#' calibration set (`kind = "soildata_like"`). Every example, test and vignette
#' in this package runs on these fixtures.
#'
#' @details
#' **These are simulated values, not measurements.** They are generated by
#' `data-raw/make_fixtures.R` from published literature parameters -- the
#' Jackson et al. (1996) tropical-savanna root distribution
#' (\eqn{\beta = 0.972}), a lognormal surface-SOC concentration with median
#' 25 g/kg, and a round-numbered bulk-density pedotransfer form. Nothing in
#' them is fitted to, or sampled from, any real dataset.
#'
#' Coordinates are a regular lattice inside the Cerrado bounding box rather
#' than a random scatter, so no fixture point can coincide with a survey site,
#' and the synthetic origin is obvious on inspection.
#'
#' The generator is seeded (`set.seed(20260901L)`, recorded in the fixture's
#' `meta$seed`), so both files are byte-reproducible by re-running the script.
#'
#' **What these fixtures cannot do:** reproduce any published metric. Forty
#' synthetic profiles do not yield the RMSE, coverage or effect-size figures
#' quoted in the README and the manuscript. Those are reproducible only from a
#' live fetch, via the scripts in `data-raw/`.
#'
#' `edaphos` does not bundle or redistribute third-party soil data. Real
#' profiles are the user's to obtain from the upstream services directly --
#' ISRIC WoSIS, the SoilData Dataverse, USDA-NRCS -- under those services'
#' own licences, which vary per record.
#'
#' @param kind Which fixture: `"wosis_like"` (default) or `"soildata_like"`.
#' @param what Which element: `"profiles"` (default), `"horizons"`, `"pedon"`
#'   (a single deep 9-horizon profile, `wosis_like` only), or `"all"` for the
#'   whole list including `meta`.
#' @param n Optional row cap, applied after subsetting. `NULL` returns
#'   everything.
#'
#' @return A data frame with `attr(, "synthetic") = TRUE`, or the whole fixture
#'   list when `what = "all"`.
#'
#' @references
#' Jackson RB, Canadell J, Ehleringer JR, Mooney HA, Sala OE, Schulze ED
#' (1996). A global analysis of root distributions for terrestrial biomes.
#' *Oecologia* 108:389-411.
#'
#' @export
#' @examples
#' prof <- edaphos_example_profiles()
#' str(prof[, c("profile_id", "soc_topsoil_gkg", "soilgrids_clay")])
#'
#' # Horizons of the first profile.
#' h <- edaphos_example_profiles(what = "horizons")
#' head(h[h$profile_id == prof$profile_id[1], ])
#'
#' # Simulated, and it says so.
#' attr(prof, "synthetic")
edaphos_example_profiles <- function(kind = c("wosis_like", "soildata_like"),
                                     what = c("profiles", "horizons",
                                              "pedon", "all"),
                                     n = NULL) {
  kind <- match.arg(kind)
  what <- match.arg(what)

  path <- system.file("extdata", .edaphos_fixture_files[[kind]],
                      package = "edaphos")
  if (!nzchar(path)) {
    stop("fixture '", .edaphos_fixture_files[[kind]], "' not found. ",
         "Re-run data-raw/make_fixtures.R.", call. = FALSE)
  }
  fx <- readRDS(path)

  .edaphos_fixture_announce()

  if (what == "all") return(fx)

  if (is.null(fx[[what]])) {
    stop("fixture '", kind, "' has no element '", what, "'; available: ",
         paste(setdiff(names(fx), "meta"), collapse = ", "), call. = FALSE)
  }
  out <- fx[[what]]
  if (!is.null(n) && is.data.frame(out) && n < nrow(out)) {
    out <- out[seq_len(n), , drop = FALSE]
    rownames(out) <- NULL
  }
  attr(out, "synthetic") <- TRUE
  out
}
