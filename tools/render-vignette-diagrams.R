#!/usr/bin/env Rscript
# ---------------------------------------------------------------------------
# tools/render-vignette-diagrams.R -- render the vignettes' Graphviz diagrams
# to static SVG.
#
# WHY. capstone-cerrado-campaign and causal-discovery-trio each drew one
# diagram with DiagrammeR::grViz(), an htmlwidget. A widget carries its
# JavaScript runtime into the self-contained vignette HTML: 2.1 MB per
# vignette, against 0.5 MB and 0.08 MB of actual figures. Those two widgets
# alone put the source tarball at 5.09 MB, over CRAN's 5 MB cap. Rendered
# once to SVG, the same diagrams cost a few kilobytes and stay vector.
#
# The DOT source lives in vignettes/diagrams/*.gv. Each SVG records the
# sha256 of the .gv it came from, and tests/testthat/test-vignette-diagrams.R
# fails if a diagram is edited without re-running this script.
#
#   Rscript tools/render-vignette-diagrams.R
#
# Needs DiagrammeR and DiagrammeRsvg -- here only, not in the package.
# ---------------------------------------------------------------------------
if (!file.exists("DESCRIPTION")) stop("run from the package root")
for (p in c("DiagrammeR", "DiagrammeRsvg", "digest"))
  if (!requireNamespace(p, quietly = TRUE)) stop("Install `", p, "`.")

for (gv in list.files("vignettes/diagrams", "[.]gv$", full.names = TRUE)) {
  src <- paste(readLines(gv, warn = FALSE, encoding = "UTF-8"), collapse = "\n")
  svg <- DiagrammeRsvg::export_svg(DiagrammeR::grViz(src))
  stamp <- sprintf("<!-- generated by tools/render-vignette-diagrams.R from %s; sha256 %s -->",
                   gv, digest::digest(src, algo = "sha256", serialize = FALSE))
  # The stamp goes after the XML declaration, where a comment is valid.
  svg <- sub("(<\\?xml[^>]*\\?>)", paste0("\\1\n", stamp), svg)
  if (!grepl(stamp, svg, fixed = TRUE)) svg <- paste0(stamp, "\n", svg)
  out <- file.path("vignettes", "figures",
                   sub("[.]gv$", ".svg", basename(gv)))
  con <- file(out, "w", encoding = "UTF-8"); writeLines(svg, con); close(con)
  cat(sprintf("%-46s %6.1f KB\n", out, file.size(out) / 1024))
}
