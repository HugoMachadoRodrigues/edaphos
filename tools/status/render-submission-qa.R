#!/usr/bin/env Rscript
# ---------------------------------------------------------------------------
# tools/status/render-submission-qa.R -- regenerate the QA block of
# inst/rosc/submission.md from measurements.
#
# WHY THIS EXISTS. submission.md is the document written for external
# reviewers, and every number in its self-report was typed by hand and wrong:
#
#   "Unit tests: 50+ test files, 1 345 expectations"  -> 91 files, 2 151
#   "14 vignettes covering all 10 pillars"            -> 19
#   "[x] builds with 0 errors / 0 notes"              -> Status: 2 NOTEs
#
# The 1 345 figure is the same one NEWS.md explicitly withdrew as
# unreproducible; submission.md was the last place still asserting it. A
# self-report to reviewers is exactly the document where a hand-typed number
# is least defensible, so the block is now derived from tools/status/facts.json
# the same way cran-comments.md is.
#
# THE CHECK TICK IS NOT A TICK ANY MORE. It reports whatever the log says. A
# checklist item that can only ever render as [x] is decoration, not a check.
#
#   Rscript tools/status/facts.R
#   Rscript tools/status/render-submission-qa.R
# ---------------------------------------------------------------------------

root <- normalizePath(file.path(dirname(sub("^--file=", "", grep("^--file=",
          commandArgs(FALSE), value = TRUE)[1])), "..", ".."), mustWork = TRUE)
setwd(root)

facts <- jsonlite::fromJSON("tools/status/facts.json", simplifyVector = TRUE)
`%||%` <- function(a, b) if (is.null(a) || !length(a) ||
                            (length(a) == 1L && is.na(a))) b else a

PATH <- "inst/rosc/submission.md"
if (!file.exists(PATH)) stop(PATH, " is not in this checkout", call. = FALSE)
md <- readLines(PATH, warn = FALSE)

tr <- facts$tests_run
ts <- facts$tests_static
ck <- facts$check
dc <- facts$docs

n_pass  <- tr$passed %||% NA_integer_
n_files <- ts$test_file_count %||% (tr$files %||% NA_integer_)
n_blocks <- ts$test_that_blocks %||% NA_integer_
n_vign  <- dc$vignette_count %||% NA_integer_
n_art   <- dc$article_count %||% 0L
status  <- ck$status_line %||% "not measured"
n_err   <- ck$n_errors %||% NA_integer_
n_warn  <- ck$n_warnings %||% NA_integer_
n_note  <- ck$n_notes %||% NA_integer_

num <- function(x) if (is.na(x)) "?" else formatC(x, big.mark = " ", format = "d")

# The check line states the outcome rather than asserting a pass. If a reader
# has to trust the tick, the tick is worthless.
check_line <- if (is.na(n_err)) {
  "- **`R CMD check --as-cran`**: not measured in this tree."
} else if (n_err == 0L && n_warn == 0L && n_note == 0L) {
  sprintf("- **`R CMD check --as-cran`**: `%s`.", status)
} else {
  sprintf(paste("- **`R CMD check --as-cran`**: `%s` (%s error(s), %s",
                "warning(s), %s note(s)). The per-item breakdown, including",
                "which items are package defects and which are artefacts of",
                "the checking machine, is in [`cran-comments.md`](../../cran-comments.md);",
                "the log itself is committed at",
                "[`tools/status/check.log`](../../tools/status/check.log)."),
          status, num(n_err), num(n_warn), num(n_note))
}

block <- c(
  "<!-- BEGIN GENERATED QA -- edit tools/status/render-submission-qa.R, not this -->",
  "",
  sprintf(paste("- **Unit tests**: %s passing expectations across %s",
                "`test_that` blocks in %s test files, from a real run.",
                "Coverage spans every pillar's edge cases (NA inputs,",
                "degenerate matrices, reproducibility, device dispatch)."),
          num(n_pass), num(n_blocks), num(n_files)),
  "- **Examples**: every exported function has at least one `@examples`",
  "  block (some are `\\dontrun{}` because they need the torch runtime,",
  "  network access, or a live Ollama instance).",
  sprintf(paste("- **Vignettes**: %s vignettes, plus %s longer-form",
                "articles that are `.Rbuildignore`d to keep the vignette",
                "build tractable."),
          num(n_vign), num(n_art)),
  check_line,
  sprintf(paste("- These figures are generated by",
                "`tools/status/render-submission-qa.R` from",
                "`tools/status/facts.json`, which is written from a real test",
                "run and a real check log. Do not edit them by hand: this",
                "block previously claimed 1 345 expectations, 14 vignettes",
                "and 0 notes, none of which was true.")),
  "",
  "<!-- END GENERATED QA -->"
)

# THE VERSION, TOO. The header and the Version field said 3.10.0 -- a release
# NEWS.md withdrew as unreproducible -- while the generated block eighty lines
# below conceded 0.9.0, so the document contradicted itself about the single
# most basic fact it states to a reviewer. Both lines are now derived.
ver <- facts$description$version %||% as.character(utils::packageVersion("edaphos"))
md <- sub("^# rOpenSci pre-submission inquiry .*$",
          sprintf("# rOpenSci pre-submission inquiry \u2014 edaphos v%s", ver), md)
md <- sub("^- \\*\\*Version\\*\\*: .*$",
          sprintf("- **Version**: %s", ver), md)

b <- grep("^<!-- BEGIN GENERATED QA", md)
e <- grep("^<!-- END GENERATED QA", md)
if (length(b) == 1L && length(e) == 1L && e > b) {
  md <- c(md[seq_len(b - 1L)], block, md[(e + 1L):length(md)])
} else {
  # First run: replace the hand-written self-report section wholesale.
  start <- grep("^## Quality-assurance self-report\\s*$", md)
  if (length(start) != 1L)
    stop("cannot locate the '## Quality-assurance self-report' heading in ",
         PATH, "; refusing to guess where the block goes", call. = FALSE)
  rest <- md[(start + 1L):length(md)]
  nxt  <- grep("^## ", rest)[1]
  if (is.na(nxt))
    stop("no section follows the self-report heading; refusing to rewrite to ",
         "end of file", call. = FALSE)
  end <- start + nxt - 1L
  md <- c(md[seq_len(start)], "", block, "", md[end:length(md)])
}

writeLines(md, PATH)
cat(sprintf("patched %s: %s expectations, %s files, %s vignettes, %s\n",
            PATH, num(n_pass), num(n_files), num(n_vign), status))
